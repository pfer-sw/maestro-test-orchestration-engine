/**
 * export-jira.js
 * Push coverage data and failing flow bugs to Jira.
 *
 * Usage:
 *   node scripts/export-jira.js [--flavor=<id>|all] [--dry-run]   (flavor ids from config/flavors.json)
 *
 * When Claude runs this via MCP, it uses mcp__claude_ai_Atlassian__ tools.
 * When run as a script, it uses the Jira REST API via jira-client.js.
 */

import 'dotenv/config';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { readFileSync, existsSync, readdirSync, mkdirSync, writeFileSync } from 'fs';
import minimist from 'minimist';

import { loadTaxonomy, getFlowsForFlavor } from './lib/coverage-tracker.js';
import {
  getJiraConfig,
  findOrCreateDashboardIssue,
  updateDashboardIssue,
  addComment,
  findExistingFlowBug,
  createFlowBug,
} from './lib/jira-client.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

const args = minimist(process.argv.slice(2));
const flavorArg = args.flavor ?? 'all';
const dryRun = !!args['dry-run'];

const flavorsConfig = JSON.parse(readFileSync(resolve(ROOT, 'config', 'flavors.json'), 'utf8'));
const targetFlavors = flavorArg === 'all'
  ? Object.keys(flavorsConfig.flavors)
  : [flavorArg];

// ── Coverage Report Markdown ──────────────────────────────────────────────────

function buildDashboardMarkdown(taxonomy, targetFlavors) {
  const now = new Date().toISOString();
  const lines = [
    `# Maestro MCP Test Coverage Dashboard`,
    ``,
    `*Last updated: ${now}*`,
    ``,
    `## Coverage Summary`,
    ``,
    `| Flavor | Total | Covered | Failing | Not Covered | Discovered | Coverage | Target | Status |`,
    `|--------|-------|---------|---------|-------------|------------|----------|--------|--------|`,
  ];

  for (const flavorId of targetFlavors) {
    const s = taxonomy.coverageSummary[flavorId];
    if (!s) continue;
    const status = s.targetMet ? '✅ Met' : '❌ Below';
    lines.push(
      `| ${flavorId} | ${s.total} | ${s.covered} | ${s.failing} | ${s.not_covered} | ${s.discovered} | ${s.coveragePercent}% | ${s.target}% | ${status} |`
    );
  }

  lines.push('', '## Coverage by Feature', '');

  for (const feature of taxonomy.features) {
    lines.push(`### ${feature.name}`);
    lines.push(`| Flow | Priority | ${targetFlavors.join(' | ')} |`);
    lines.push(`|------|----------|${'---------|'.repeat(targetFlavors.length)}`);
    for (const flow of feature.flows) {
      const cells = targetFlavors.map((f) => {
        if (!feature.appliesTo.includes(f)) return 'N/A';
        const cov = flow.coverage[f];
        if (!cov) return 'N/A';
        const emoji = { covered: '✅', failing: '❌', not_covered: '⬜', discovered: '🔍', skipped: '⏭' };
        return `${emoji[cov.status] ?? '?'} ${cov.status}`;
      });
      lines.push(`| ${flow.name} | ${flow.priority} | ${cells.join(' | ')} |`);
    }
    lines.push('');
  }

  // Failing flows section
  const allFailing = [];
  for (const flavorId of targetFlavors) {
    const flows = getFlowsForFlavor(taxonomy, flavorId);
    for (const flow of flows) {
      if (flow.coverage[flavorId]?.status === 'failing') {
        allFailing.push({ flavorId, flow });
      }
    }
  }

  if (allFailing.length > 0) {
    lines.push('## ❌ Failing Flows', '');
    for (const { flavorId, flow } of allFailing) {
      const reason = flow.coverage[flavorId]?.failureReason ?? 'Unknown';
      lines.push(`- **[${flavorId}]** ${flow.name} (\`${flow.id}\`)`);
      lines.push(`  - Error: \`${reason.slice(0, 100)}\``);
    }
    lines.push('');
  }

  lines.push(`---`, `*Generated by [Maestro MCP Testing Framework](https://github.com/mobile-dev-inc/maestro-mcp)*`);
  return lines.join('\n');
}

// ── Failing Flow Bug Management ───────────────────────────────────────────────

async function syncFailingFlowBugs(taxonomy, targetFlavors, jiraConfig, dry) {
  let created = 0, updated = 0;

  for (const flavorId of targetFlavors) {
    const flows = getFlowsForFlavor(taxonomy, flavorId);
    for (const flow of flows) {
      if (flow.coverage[flavorId]?.status !== 'failing') continue;

      const error = flow.coverage[flavorId].failureReason;
      const flowPath = flow.flowFile ? resolve(ROOT, flow.flowFile) : null;
      const flowYaml = flowPath && existsSync(flowPath) ? readFileSync(flowPath, 'utf8') : null;

      // Find the most recent failure screenshot
      const failureDir = resolve(ROOT, 'screenshots', 'failures');
      let screenshotPath = null;
      if (existsSync(failureDir)) {
        const screenshots = readdirSync(failureDir)
          .filter((f) => f.includes(flow.id.replace(/\./g, '_')))
          .sort()
          .reverse();
        if (screenshots[0]) screenshotPath = resolve(failureDir, screenshots[0]);
      }

      if (dry) {
        console.log(`[dry-run] Would sync bug for: ${flow.id} (${flavorId})`);
        continue;
      }

      try {
        const existing = await findExistingFlowBug(flow.id, flavorId, jiraConfig);
        if (existing) {
          await addComment(existing.key,
            `🔄 Flow still failing as of ${new Date().toISOString()}\n\nError: ${error ?? 'Unknown'}\nScreenshot: ${screenshotPath ?? 'N/A'}`,
            jiraConfig
          );
          console.log(`   Updated bug: ${existing.key} (${flow.id})`);
          updated++;
        } else {
          const issueKey = await createFlowBug({
            flowId: flow.id,
            flowName: flow.name,
            flavorId,
            error,
            flowYaml,
            screenshotPath,
          }, jiraConfig);
          console.log(`   Created bug: ${issueKey} (${flow.id})`);
          created++;
        }
      } catch (err) {
        console.warn(`   ⚠ Jira sync failed for ${flow.id}: ${err.message}`);
      }
    }
  }
  return { created, updated };
}

// ── Main ──────────────────────────────────────────────────────────────────────

async function main() {
  const taxonomy = loadTaxonomy();

  console.log(`\n📤 Exporting to Jira`);
  console.log(`   Flavors: ${targetFlavors.join(', ')}`);
  if (dryRun) console.log(`   DRY RUN — no Jira changes will be made`);

  let jiraConfig;
  try {
    jiraConfig = getJiraConfig();
    if (!jiraConfig.apiToken || !jiraConfig.baseUrl) {
      console.warn('⚠ Jira credentials not configured. Set JIRA_* env vars in .env');
      console.warn('  Writing coverage to reports/coverage/ instead.');
      writeLocalFallback(taxonomy);
      return;
    }
  } catch (err) {
    console.warn(`⚠ Could not load Jira config: ${err.message}`);
    writeLocalFallback(taxonomy);
    return;
  }

  // Build dashboard markdown
  const dashboardMd = buildDashboardMarkdown(taxonomy, targetFlavors);

  // Update dashboard issue
  try {
    if (!dryRun) {
      const issueKey = await findOrCreateDashboardIssue(jiraConfig);
      await updateDashboardIssue(issueKey, dashboardMd, jiraConfig);
      console.log(`   ✓ Dashboard updated: ${jiraConfig.baseUrl}/browse/${issueKey}`);
    } else {
      console.log(`[dry-run] Would update dashboard issue`);
      console.log(dashboardMd.slice(0, 300) + '...');
    }
  } catch (err) {
    console.warn(`   ⚠ Dashboard update failed: ${err.message}`);
  }

  // Sync failing flow bugs
  console.log(`\n   Syncing failing flow bugs...`);
  const { created, updated } = await syncFailingFlowBugs(taxonomy, targetFlavors, jiraConfig, dryRun);
  console.log(`   Bugs created: ${created}, updated: ${updated}`);

  console.log(`\n✅ Jira export complete\n`);
}

function writeLocalFallback(taxonomy) {
  const outDir = resolve(ROOT, 'reports', 'coverage');
  mkdirSync(outDir, { recursive: true });
  const outPath = resolve(outDir, `coverage-${Date.now()}.json`);
  writeFileSync(outPath, JSON.stringify(taxonomy.coverageSummary, null, 2), 'utf8');
  console.log(`   Coverage written to: ${outPath}`);
}

main().catch((err) => {
  console.error('Jira export failed:', err);
  process.exit(1);
});
